require("dotenv").config({ path: require("path").resolve(__dirname, "../.env") });

const { Pool } = require("pg");

function requireEnv(name) {
  const value = process.env[name]?.trim();
  if (!value) throw new Error(`${name} wajib diatur di file .env.`);
  return value;
}

const pool = new Pool(process.env.DATABASE_URL
  ? {
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.DATABASE_SSL === "true" ? { rejectUnauthorized: false } : undefined,
    }
  : {
      user: requireEnv("PGUSER"),
      host: requireEnv("PGHOST"),
      database: requireEnv("PGDATABASE"),
      password: requireEnv("PGPASSWORD"),
      port: Number(requireEnv("PGPORT")),
    });

async function jalankanMigrasi() {
  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS user_session (
        sid VARCHAR NOT NULL PRIMARY KEY,
        sess JSON NOT NULL,
        expire TIMESTAMP(6) NOT NULL
      );
      CREATE INDEX IF NOT EXISTS idx_user_session_expire ON user_session (expire);
      CREATE TABLE IF NOT EXISTS workspace (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS admin (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        workspace_id BIGINT NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
        nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
        email TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        mfa_secret TEXT,
        mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
    `);
    await pool.query("ALTER TABLE admin ADD COLUMN IF NOT EXISTS mfa_secret TEXT");
    await pool.query("ALTER TABLE admin ADD COLUMN IF NOT EXISTS mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE");
    await pool.query(`
      CREATE TABLE IF NOT EXISTS karyawan (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        workspace_id BIGINT REFERENCES workspace(id) ON DELETE CASCADE,
        nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
        feature JSONB NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        archived_at TIMESTAMPTZ
      );
      CREATE TABLE IF NOT EXISTS log_absen (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        workspace_id BIGINT REFERENCES workspace(id) ON DELETE CASCADE,
        karyawan_id BIGINT REFERENCES karyawan(id) ON DELETE RESTRICT,
        waktu TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        aktivitas TEXT NOT NULL,
        status_proses TEXT NOT NULL CHECK (status_proses IN ('Sukses', 'Gagal')),
        status_kehadiran TEXT CHECK (
          status_kehadiran IS NULL
          OR (
            status_kehadiran IN ('awal', 'terlambat')
            AND status_proses = 'Sukses'
            AND aktivitas = 'Absen Masuk'
          )
        )
      );
      CREATE TABLE IF NOT EXISTS pengaturan_absensi (
        workspace_id BIGINT REFERENCES workspace(id) ON DELETE CASCADE,
        jam_masuk TIME NOT NULL DEFAULT TIME '07:00',
        zona_waktu TEXT NOT NULL DEFAULT 'Asia/Jakarta'
      );
    `);

    const workspaceResult = await pool.query(
      `INSERT INTO workspace (nama)
       SELECT 'Ruang Kerja Lama'
       WHERE NOT EXISTS (SELECT 1 FROM workspace)
       RETURNING id`,
    );
    let workspaceId;
    if (workspaceResult.rowCount) workspaceId = workspaceResult.rows[0].id;
    else workspaceId = (await pool.query("SELECT id FROM workspace ORDER BY id LIMIT 1")).rows[0]?.id;
    if (!workspaceId) throw new Error("Gagal membuat ruang kerja migrasi.");

    await pool.query("ALTER TABLE karyawan ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspace(id) ON DELETE CASCADE");
    await pool.query("UPDATE karyawan SET workspace_id = $1 WHERE workspace_id IS NULL", [workspaceId]);
    await pool.query("ALTER TABLE karyawan ALTER COLUMN workspace_id SET NOT NULL");

    await pool.query("ALTER TABLE log_absen ADD COLUMN IF NOT EXISTS workspace_id BIGINT REFERENCES workspace(id) ON DELETE CASCADE");
    await pool.query("UPDATE log_absen SET workspace_id = $1 WHERE workspace_id IS NULL", [workspaceId]);
    await pool.query("ALTER TABLE log_absen ALTER COLUMN workspace_id SET NOT NULL");

    await pool.query("ALTER TABLE pengaturan_absensi ADD COLUMN IF NOT EXISTS workspace_id BIGINT");
    await pool.query("UPDATE pengaturan_absensi SET workspace_id = $1 WHERE workspace_id IS NULL", [workspaceId]);
    await pool.query("ALTER TABLE pengaturan_absensi ALTER COLUMN workspace_id SET NOT NULL");
    await pool.query(
      "DO $$ BEGIN IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='pengaturan_absensi' AND column_name='id') THEN ALTER TABLE pengaturan_absensi DROP CONSTRAINT IF EXISTS pengaturan_absensi_pkey; END IF; END $$;",
    );
    await pool.query(`
      DO $$ BEGIN
        IF NOT EXISTS (
          SELECT 1 FROM pg_constraint
          WHERE conrelid = 'pengaturan_absensi'::regclass AND contype = 'p'
        ) THEN
          ALTER TABLE pengaturan_absensi ADD PRIMARY KEY (workspace_id);
        END IF;
      END $$;
    `);
    await pool.query("ALTER TABLE pengaturan_absensi DROP COLUMN IF EXISTS id");
    await pool.query(`
      DO $$ BEGIN
        IF NOT EXISTS (
          SELECT 1
          FROM pg_constraint
          WHERE conname = 'pengaturan_absensi_workspace_fk'
            AND conrelid = 'pengaturan_absensi'::regclass
        ) THEN
          ALTER TABLE pengaturan_absensi
            ADD CONSTRAINT pengaturan_absensi_workspace_fk
            FOREIGN KEY (workspace_id) REFERENCES workspace(id)
            ON DELETE CASCADE NOT VALID;
        END IF;
      END $$;
    `);

    await pool.query("CREATE INDEX IF NOT EXISTS idx_admin_workspace_id ON admin(workspace_id)");
    await pool.query("CREATE INDEX IF NOT EXISTS idx_karyawan_active_nama ON karyawan (workspace_id, nama, id) WHERE archived_at IS NULL");
    await pool.query("CREATE INDEX IF NOT EXISTS idx_log_absen_karyawan_id ON log_absen (workspace_id, karyawan_id)");

    console.log("Migrasi auth dan workspace selesai. Data lama ditempatkan di ruang kerja lama.");
  } catch (error) {
    console.error("Gagal migrasi:", error);
    process.exitCode = 1;
  } finally {
    await pool.end();
  }
}

jalankanMigrasi();

CREATE INDEX idx_karyawan_active_nama
    ON karyawan (nama, id)
    WHERE archived_at IS NULL;

CREATE INDEX idx_log_absen_karyawan_id
    ON log_absen (karyawan_id);

CREATE INDEX idx_log_absen_waktu
    ON log_absen (waktu DESC, id DESC);

CREATE TABLE user_session (
    sid VARCHAR NOT NULL PRIMARY KEY,
    sess JSON NOT NULL,
    expire TIMESTAMP(6) NOT NULL
);

CREATE INDEX idx_user_session_expire ON user_session (expire);

CREATE TABLE workspace (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE admin (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_admin_workspace_id ON admin(workspace_id);

CREATE TABLE karyawan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    nama TEXT NOT NULL CHECK (BTRIM(nama) <> ''),
    feature JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    archived_at TIMESTAMPTZ
);

CREATE TABLE log_absen (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    karyawan_id BIGINT REFERENCES karyawan(id) ON DELETE RESTRICT,
    waktu TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    aktivitas TEXT NOT NULL,
    status_proses TEXT NOT NULL CHECK (status_proses IN ('Sukses', 'Gagal')),
    status_kehadiran TEXT CHECK (
        status_kehadiran IS NULL
        OR (
            status_kehadiran IN ('awal', 'terlambat')
            AND status_proses = 'Sukses'
            AND aktivitas = 'Absen Masuk'
        )
    )
);

CREATE TABLE pengaturan_absensi (
    workspace_id BIGINT PRIMARY KEY REFERENCES workspace(id) ON DELETE CASCADE,
    jam_masuk TIME NOT NULL DEFAULT TIME '07:00',
    zona_waktu TEXT NOT NULL DEFAULT 'Asia/Jakarta'
);

CREATE INDEX idx_karyawan_active_nama
    ON karyawan (workspace_id, nama, id)
    WHERE archived_at IS NULL;

CREATE INDEX idx_log_absen_karyawan_id
    ON log_absen (workspace_id, karyawan_id);

CREATE INDEX idx_log_absen_waktu
    ON log_absen (waktu DESC, id DESC);
